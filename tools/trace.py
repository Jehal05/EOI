#!/usr/bin/env python3
"""Traceability matrix: docs/traceability.json (requirement -> code, tests, e2e suites, benchmarks, UI, doc) is CHECKED here:
every referenced file must exist, every test file must contain tests (counted), every e2e script must appear in the last
conformance run (docs/conformance_run.json) and have passed, every claimed 'met' needs code, tests or e2e evidence.
Writes docs/TRACEABILITY.md. Exit 1 when a reference dangles or a 'met' row has no evidence."""
import json, os, re, sys
ROOT = os.path.join(os.path.dirname(__file__), "..")
reg = json.load(open(f"{ROOT}/docs/traceability.json"))["requirements"]
run = {}
rp = f"{ROOT}/docs/conformance_run.json"
if os.path.exists(rp):
    for s in json.load(open(rp))["suites"]: run[s["name"]] = s
PAT = {".py": r"^\s*def test_", ".go": r"^func (Test|Fuzz)", ".rs": r"#\[test\]", ".ts": r"\b(it|test)\(", ".java": r"T\.ok\("}
def count_tests(path):
    ext = os.path.splitext(path)[1]; txt = open(f"{ROOT}/{path}").read()
    if path.endswith("usability.py"): return len(re.findall(r"^def selftest_|^    def test_", txt, re.M))
    return len(re.findall(PAT.get(ext, r"$^"), txt, re.M))
bad = []; rows = []
E2E_NAME = lambda p: os.path.splitext(os.path.basename(p))[0]
for r in reg:
    probs = []; ntests = 0
    for k in ("code", "tests", "e2e", "bench", "ui"):
        for p in r[k]:
            if not os.path.exists(f"{ROOT}/{p}"): probs.append(f"missing {k}: {p}")
    for p in r["tests"]:
        if os.path.exists(f"{ROOT}/{p}"):
            n = count_tests(p); ntests += n
            if n == 0: probs.append(f"no tests found in {p}")
    ev = []
    for p in r["e2e"]:
        nm = E2E_NAME(p); cands = [s for n, s in run.items() if n == nm or n.startswith(nm + "_") or n == nm.replace("tools/", "")]
        if run and not cands: probs.append(f"{p} not in the last conformance run")
        elif cands: ev.append(f"{nm}: " + ("pass" if all(c["ok"] for c in cands) else "FAIL") + f" ({'/'.join(str(c['passed']) for c in cands)})")
        if cands and not all(c["ok"] for c in cands): probs.append(f"{p} failed in the last conformance run")
    for sn in r.get("suites", []):
        if run and sn not in run: probs.append(f"suite {sn} not in the last conformance run")
        elif sn in run:
            ev.append(f"{sn}: " + ("pass" if run[sn]["ok"] else "FAIL")); 
            if not run[sn]["ok"]: probs.append(f"suite {sn} failed")
    if r["status"] == "met" and not (r["tests"] or r["e2e"] or r["bench"] or r.get("suites")): probs.append("status met but no tests, e2e or benchmark")
    if probs: bad.append((r["id"], probs))
    rows.append((r, ntests, ev, probs))
cnt = {}
for r, *_ in rows: cnt[r["status"]] = cnt.get(r["status"], 0) + 1
L = ["# Traceability matrix", "", "Generated by `tools/trace.py` from `docs/traceability.json`; every path below was checked to exist, test counts are counted from the files, and e2e results come from the last full run recorded in `docs/conformance_run.json`.", "",
     f"Rows: {len(rows)} · " + " · ".join(f"{k}: {v}" for k, v in sorted(cnt.items())) + f" · dangling references: {sum(len(p) for _, p in bad)}", "",
     "| ID | Requirement | Status | Code | Unit tests (count) | Live / browser evidence | Benchmark | UI | Limit |", "|---|---|---|---|---|---|---|---|---|"]
short = lambda p: "`" + p.replace("services/", "").replace("ems-analytics/", "ems/")[-46:] + "`"
for r, n, ev, probs in rows:
    L.append(f"| {r['id']} | {r['text']} ({r['source']}) | **{r['status']}**{' ⚠ ' + '; '.join(probs) if probs else ''} | {'<br>'.join(short(p) for p in r['code'])} | {'<br>'.join(short(p) for p in r['tests'])}{f' ({n})' if r['tests'] else ''} | {'<br>'.join(ev) if ev else ('<br>'.join(short(p) for p in r['e2e']) if r['e2e'] else '')} | {'<br>'.join(short(p) for p in r['bench'])} | {'<br>'.join(short(p) for p in r['ui'])} | {r['limit']} |")
L += ["", "Status words: **met** = meets the item's Definition of Done within the limits stated; **partial** = built and tested but a named part of the requirement is missing or only simulated; **not built** = nothing to run.", ""]
open(f"{ROOT}/docs/TRACEABILITY.md", "w").write("\n".join(L) + "\n")
print(f"{len(rows)} requirements; {len(bad)} with problems")
for i, p in bad: print(" ", i, "; ".join(p))
sys.exit(1 if bad else 0)
