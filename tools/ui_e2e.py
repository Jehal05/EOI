def axe(page, label):
    page.evaluate(open(AXE).read())      # via DevTools protocol: the page CSP (correctly) blocks injected <script> tags
    r = page.evaluate("async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,impact:v.impact,n:v.nodes.length,help:v.help}))}")
    serious = [v for v in r if v["impact"] in ("serious", "critical")]
    print(f"       axe[{label}]: {len(r)} rule violations ({len(serious)} serious/critical) " + (json.dumps(r)[:400] if r else ""))
    return r, serious

